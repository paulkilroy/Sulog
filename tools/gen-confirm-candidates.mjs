#!/usr/bin/env node
/* Bake per-word CANDIDATES for the dictionary-confirm queue into the app bundle, so each
 * unconfirmed entry renders like the missing-answers cards: cited multiple-choice options.
 *   option 1 — the gloss as it entered the app, cited to WHO authored it (docs/word-bank/origins.json,
 *              traced per word via git archaeology; PC-drilled rows = the Gemini book extraction)
 *   option 2 — Tramp's own printed gloss (with page), when the headword is in Tramp
 * plus a pronunciation-guide prefill derived from Tramp's accented headword when the row lacks one.
 *
 * Writes src/courses/waray/confirm-candidates.js — runs inside `npm run reload` (before build),
 * so the bundle always matches the DB queue. Needs SUPABASE_DB_URL.
 */
import fs from "fs";
import pg from "pg";

// --- transliterator (verbatim from tools/build-respellings.mjs / fill-pronunciation.mjs) ---
function syllabify(w) {
  w = w.toLowerCase().replace(/ng/g, "ŋ");
  const out = [];
  w.split("-").forEach((g, gi) => {
    const units = []; const re = /([^aeiou]*)([aeiou])/g; let m, last = 0;
    while ((m = re.exec(g))) { units.push({ o: m[1], v: m[2] }); last = re.lastIndex; }
    const tail = g.slice(last);
    if (!units.length) { if (g) out.push({ syl: g, glottalBefore: gi > 0 }); return; }
    const syls = units.map((u) => u.o + u.v);
    for (let k = 0; k < units.length - 1; k++) { const on = units[k + 1].o; if (on.length >= 2) { syls[k] += on.slice(0, -1); syls[k + 1] = on.slice(-1) + units[k + 1].v; } }
    if (tail) syls[syls.length - 1] += tail;
    syls.forEach((s, si) => out.push({ syl: s, glottalBefore: gi > 0 && si === 0 }));
  });
  return out;
}
function respellSyl(syl) {
  syl = syl.replace(/ŋ/g, "ng");
  const m = syl.match(/^([^aeiou]*)([aeiou])([^aeiou]*)$/i);
  if (!m) return syl;
  let [, onset, v, coda] = m; v = v.toLowerCase(); let vowel;
  if (v === "a" && /^y/i.test(coda)) { vowel = "igh"; coda = coda.slice(1); }
  else if (v === "a" && /^w/i.test(coda)) { vowel = "ow"; coda = coda.slice(1); }
  else { const closed = coda.length > 0; vowel = { a: closed ? "a" : "ah", e: closed ? "e" : "eh", i: closed ? "i" : "ee", o: "o", u: "oo" }[v]; }
  const cmap = (s) => s.replace(/c/gi, "k");
  return cmap(onset) + vowel + cmap(coda);
}
function respell(word, stressIdxV) {
  word = word.toLowerCase().replace(/[^a-z-]/g, "");
  const syls = syllabify(word);
  if (!syls.length) return word;
  const n = syls.length;
  if (n === 1) return respellSyl(syls[0].syl);
  const stress = stressIdxV && stressIdxV >= 1 && stressIdxV <= n ? stressIdxV - 1 : Math.max(0, n - 2);
  return syls.map((s, i) => { let r = respellSyl(s.syl); if (i === stress) r = r.toUpperCase(); return r; }).join("-");
}
const stripAcc = (s) => (s || "").toLowerCase().normalize("NFD").replace(/[̀-ͯ]/g, "");
function stressIdx(accented) {
  if (!accented) return 0;
  const s = accented.toLowerCase().normalize("NFD"); let vi = 0, stress = 0;
  for (let i = 0; i < s.length; i++) if ("aeiou".includes(s[i])) { vi++; if (/[̀́]/.test(s[i + 1] || "")) stress = vi; }
  return stress;
}

const ORIGINS = JSON.parse(fs.readFileSync("docs/word-bank/origins.json", "utf8"));
const tramp = JSON.parse(fs.readFileSync("docs/sources/dictionaries/tramp.json", "utf8")).entries;
const byNorm = new Map();
for (const e of tramp) { if (!byNorm.has(e.norm)) byNorm.set(e.norm, []); byNorm.get(e.norm).push(e); }

const c = new pg.Client({ connectionString: process.env.SUPABASE_DB_URL, ssl: { rejectUnauthorized: false } });
await c.connect();
const rows = (await c.query(`select d.waray, d.meaning, d.pronunciation,
    exists (select 1 from block_items bi join lesson_blocks lb on lb.id=bi.block_id
            where bi.dict_waray = d.waray and lb.lesson_id like 'pc-%') as pc
  from dictionary d where not d.confirmed order by d.waray`)).rows;
await c.end();

const out = {};
for (const r of rows) {
  const key = stripAcc(r.waray).replace(/[^a-z-]/g, "");
  const hits = /\s/.test(r.waray.trim()) ? [] : (byNorm.get(key) || []);
  const cand = {
    origin: ORIGINS[r.waray] || (r.pc ? "Gemini · Peace Corps scan" : "course deck (origin untraced)"),
  };
  if (hits.length) {
    cand.tramp = {
      gloss: hits.map((h) => (h.gloss || "").trim()).join(" / ").slice(0, 160),
      page: hits[0].page || null,
    };
    const acc = hits.find((h) => /[̀-ͯ]/.test(h.waray.normalize("NFD")));
    if (acc) cand.pron = respell(key, stressIdx(acc.waray));
  }
  if (!cand.pron && !r.pronunciation && !/\s/.test(r.waray.trim())) cand.pron = respell(key, 0);
  out[r.waray] = cand;
}
fs.writeFileSync("src/courses/waray/confirm-candidates.js",
  `/* GENERATED by tools/gen-confirm-candidates.mjs — do not edit. Candidate glosses + cited
   sources for the dictionary-confirm queue (each unconfirmed word: how it entered the app,
   and what Tramp prints). Regenerated on every \`npm run reload\`. */
export const CONFIRM_CANDIDATES = ${JSON.stringify(out, null, 1)};
`);
console.log(`✓ confirm-candidates.js — ${rows.length} unconfirmed word(s), ${Object.values(out).filter((x) => x.tramp).length} with a Tramp gloss`);
