/* Generate docs/schema/zorc-dictionary.sql — bulk-load the full Tramp & Zorc (1991) dictionary
   into the DB so ANY Waray word is searchable (25k headwords), not just the ~600 course words.
   - Source: docs/sources/dictionaries/tramp.json (27,021 senses / 25,376 headwords, Vision OCR).
   - Excludes words already in the live DB dictionary (the curated PC rows are NEVER touched).
   - dictionary.meaning = primary sense; every sense also goes to `meanings` (sources={tramp},
     confirmed=false). pronunciation is left null — Zorc's accent encodes stress; deriving CAPS
     guides for 25k is a separate pass (see build-respellings). `on conflict do nothing` is a
     belt-and-suspenders on top of the exclude.
   Run:  node tools/gen-zorc-dict.mjs   →   load with your SUPABASE_DB_URL (see console).            */
import fs from "fs";
import { createClient } from "@supabase/supabase-js";

const canon = (w) => (w || "").normalize("NFD").replace(/[̀-ͯ]/g, "").toLowerCase().trim();
const S = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const clean = (g) => (g || "").replace(/\s+/g, " ").trim();

// 1) existing dictionary words in the live DB — exclude them so curated rows stay untouched
const sb = createClient("https://kdtzfaobcgprivsxkger.supabase.co", "sb_publishable_mVYVK10OZfARWUl3PcfhHQ_zHa7bVpS");
const existing = new Set();
for (let from = 0; ; from += 1000) {
  const { data, error } = await sb.from("dictionary").select("waray").range(from, from + 999);
  if (error) throw new Error(error.message);
  data.forEach((r) => existing.add(r.waray));
  if (data.length < 1000) break;
}
console.log("existing DB dictionary words (excluded):", existing.size);

// 2) group Tramp senses by headword
const T = JSON.parse(fs.readFileSync("docs/sources/dictionaries/tramp.json", "utf8"));
const byHead = new Map();
for (const e of T.entries) {
  const w = canon(e.norm || e.waray);
  if (!w || existing.has(w)) continue;
  const meaning = clean(e.gloss);
  if (!meaning) continue;
  if (!byHead.has(w)) byHead.set(w, []);
  byHead.get(w).push({ meaning, pos: e.pos || null });
}
console.log("new headwords to load:", byHead.size);

// 3) emit SQL — chunked inserts
const CHUNK = 500;
const dictRows = [], meaningRows = [];
for (const [w, senses] of byHead) {
  const kind = /\s/.test(w) ? "phrase" : "word";
  const primary = senses[0];
  dictRows.push(`(${S(w)},'${kind}',${S(primary.meaning)},${S(primary.pos)},false)`);
  // dedupe identical sense text within a headword; number by order
  const seen = new Set();
  let ord = 0;
  for (const s of senses) {
    if (seen.has(s.meaning)) continue;
    seen.add(s.meaning);
    ord++;
    meaningRows.push(`(${S(w)},${S(s.meaning)},${S(s.pos)},'{tramp}',false,${ord})`);
  }
}
let sql = `-- Tramp & Zorc (1991) full dictionary — GENERATED by tools/gen-zorc-dict.mjs. Do not hand-edit.\n`
  + `-- ${byHead.size} headwords / ${meaningRows.length} senses. Excludes words already present; never clobbers curated rows.\n\n`;
for (let i = 0; i < dictRows.length; i += CHUNK)
  sql += "insert into dictionary (waray,kind,meaning,pos,confirmed) values\n  "
    + dictRows.slice(i, i + CHUNK).join(",\n  ") + "\n  on conflict (waray) do nothing;\n";
sql += "\n";
for (let i = 0; i < meaningRows.length; i += CHUNK)
  sql += "insert into meanings (waray,meaning,pos,sources,confirmed,ord) values\n  "
    + meaningRows.slice(i, i + CHUNK).join(",\n  ") + "\n  on conflict (waray,meaning) do nothing;\n";

fs.writeFileSync("docs/schema/zorc-dictionary.sql", sql);
console.log(`✓ docs/schema/zorc-dictionary.sql — dictionary +${dictRows.length} · meanings +${meaningRows.length} · ${(sql.length/1024/1024).toFixed(1)} MB`);
